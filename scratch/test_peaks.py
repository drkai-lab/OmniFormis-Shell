def get_points(path_str):
    tokens = re.findall(r'[A-Za-z]|[-+]?\d*\.?\d+(?:[eE][-+]?\d+)?', path_str)
    
    pts = []
    x, y = 0, 0
    i = 0
    while i < len(tokens):
        cmd = tokens[i]
        if cmd == 'M':
            x, y = float(tokens[i+1]), float(tokens[i+2])
            pts.append((x,y))
            i += 3
        elif cmd == 'C':
            # sample C
            cx1, cy1 = float(tokens[i+1]), float(tokens[i+2])
            cx2, cy2 = float(tokens[i+3]), float(tokens[i+4])
            cx3, cy3 = float(tokens[i+5]), float(tokens[i+6])
            
            for t in range(1, 11):
                T = t / 10.0
                nx = (1-T)**3 * x + 3*(1-T)**2*T * cx1 + 3*(1-T)*T**2 * cx2 + T**3 * cx3
                ny = (1-T)**3 * y + 3*(1-T)**2*T * cy1 + 3*(1-T)*T**2 * cy2 + T**3 * cy3
                pts.append((nx, ny))
            x, y = cx3, cy3
            i += 7
        elif cmd == 'L':
            x, y = float(tokens[i+1]), float(tokens[i+2])
            pts.append((x,y))
            i += 3
        elif cmd == 'H':
            x = float(tokens[i+1])
            pts.append((x,y))
            i += 2
        elif cmd == 'V':
            y = float(tokens[i+1])
            pts.append((x,y))
            i += 2
        elif cmd == 'Z':
            i += 1
        else:
            i += 1
    return pts

